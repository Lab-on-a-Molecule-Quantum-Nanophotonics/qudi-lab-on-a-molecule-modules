def gaussian2D(x, y, A, sigma, x0 , y0):
    return A*np.exp(-((x-x0)**2+(y-y0)**2)/(2*sigma**2))

def gaussian(x, cenu, cenv, wid):

    u = x[:, 0]
    v = x[:, 1]
    return (1/(2*np.pi*wid**2)) * np.exp(-(u-cenu)**2 / (2*wid**2)-(v-cenv)**2 / (2*wid**2))

